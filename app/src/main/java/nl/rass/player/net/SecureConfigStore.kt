package nl.rass.player.net

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import kotlinx.coroutines.CoroutineDispatcher
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.sync.Mutex
import kotlinx.coroutines.sync.withLock
import kotlinx.coroutines.withContext
import kotlinx.serialization.json.Json
import java.io.File
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/** Persistence for the private connection. Faked in tests. */
interface ProxyStore {
    suspend fun load(): ProxyStoreData
    suspend fun update(transform: (ProxyStoreData) -> ProxyStoreData): ProxyStoreData
}

/** Authenticated encryption of small blobs. */
interface BlobCipher {
    fun encrypt(plain: ByteArray, aad: ByteArray): ByteArray
    fun decrypt(blob: ByteArray, aad: ByteArray): ByteArray
}

/**
 * AES-256-GCM with a caller-supplied key. Blob layout: `[version=1][ivLen][iv][ciphertext+tag]`.
 * The IV is generated by the cipher provider (Android Keystore requires that).
 */
class AesGcmBlobCipher(private val key: () -> SecretKey) : BlobCipher {

    override fun encrypt(plain: ByteArray, aad: ByteArray): ByteArray {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, key())
        cipher.updateAAD(aad)
        val ct = cipher.doFinal(plain)
        val iv = cipher.iv
        return byteArrayOf(VERSION, iv.size.toByte()) + iv + ct
    }

    override fun decrypt(blob: ByteArray, aad: ByteArray): ByteArray {
        require(blob.size > 2 && blob[0] == VERSION) { "unknown blob format" }
        val ivLen = blob[1].toInt()
        require(ivLen in 12..16 && blob.size > 2 + ivLen) { "bad blob" }
        val iv = blob.copyOfRange(2, 2 + ivLen)
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, key(), GCMParameterSpec(128, iv))
        cipher.updateAAD(aad)
        return cipher.doFinal(blob, 2 + ivLen, blob.size - 2 - ivLen)
    }

    private companion object {
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val VERSION: Byte = 1
    }
}

/** Non-exportable AES-256 key in the Android Keystore (hardware-backed where the TV supports it). */
object AndroidKeystoreKey {
    private const val PROVIDER = "AndroidKeyStore"

    fun getOrCreate(alias: String): SecretKey {
        val ks = KeyStore.getInstance(PROVIDER).apply { load(null) }
        (ks.getEntry(alias, null) as? KeyStore.SecretKeyEntry)?.let { return it.secretKey }
        val gen = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, PROVIDER)
        gen.init(
            KeyGenParameterSpec.Builder(alias, KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT)
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(256)
                .build(),
        )
        return gen.generateKey()
    }
}

/**
 * Encrypted storage for subscription URLs, parsed configs, test results and the R10 settings (R10.6).
 *
 * Why plain Keystore + AES-GCM and not EncryptedFile/Tink: androidx.security-crypto is deprecated, and Tink
 * would add a dependency for what is one small blob. The key never leaves the Keystore; the file lives in
 * `noBackupFilesDir` (excluded from backups, and `allowBackup=false` anyway). If the key is gone (e.g. app
 * data partially restored) the blob can't be decrypted and the store starts empty; the user re-adds links.
 *
 * All writes are atomic (temp file + rename). Nothing from the store is ever logged.
 */
class SecureConfigStore(
    private val file: File,
    private val cipher: BlobCipher,
    private val io: CoroutineDispatcher = Dispatchers.IO,
) : ProxyStore {

    private val mutex = Mutex()
    private var cache: ProxyStoreData? = null
    private val json = Json { ignoreUnknownKeys = true; encodeDefaults = false }

    override suspend fun load(): ProxyStoreData = mutex.withLock { loadLocked() }

    override suspend fun update(transform: (ProxyStoreData) -> ProxyStoreData): ProxyStoreData = mutex.withLock {
        val next = transform(loadLocked())
        withContext(io) { write(next) }
        cache = next
        next
    }

    private suspend fun loadLocked(): ProxyStoreData {
        cache?.let { return it }
        val data = withContext(io) { read() }
        cache = data
        return data
    }

    private fun read(): ProxyStoreData {
        if (!file.exists()) return ProxyStoreData()
        return try {
            val plain = cipher.decrypt(file.readBytes(), AAD)
            json.decodeFromString(ProxyStoreData.serializer(), plain.decodeToString())
        } catch (e: Exception) {
            // Undecryptable or corrupt: start clean rather than crash. Nothing about the content is logged.
            ProxyStoreData()
        }
    }

    private fun write(data: ProxyStoreData) {
        val bytes = cipher.encrypt(json.encodeToString(ProxyStoreData.serializer(), data).encodeToByteArray(), AAD)
        file.parentFile?.mkdirs()
        val tmp = File(file.parentFile, file.name + ".tmp")
        tmp.outputStream().use { out ->
            out.write(bytes)
            out.fd.sync()
        }
        if (!tmp.renameTo(file)) {
            file.delete()
            check(tmp.renameTo(file)) { "could not save private connection store" }
        }
    }

    companion object {
        const val FILE_NAME = "private-connection.bin"
        const val KEY_ALIAS = "rass_private_connection_v1"
        private val AAD = "rass-player/private-connection/v1".encodeToByteArray()
    }
}
