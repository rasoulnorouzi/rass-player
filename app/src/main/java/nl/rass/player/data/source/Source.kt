package nl.rass.player.data.source

import java.util.UUID
import kotlinx.serialization.Serializable
import nl.rass.player.data.feed.FeedUrls

/**
 * One entry of Settings → Sources (R1, feed-spec §14–15). Secrets ([token], [customHeaderValue]) are plain
 * text only in memory; on disk they are encrypted ([SecretCipher]). Never log a [Source] with secrets:
 * [toString] redacts them.
 */
data class Source(
    /** Client-generated UUID (§12.5 `src:<uuid>:<id>` keys). */
    val id: String,
    val name: String,
    val url: String,
    val enabled: Boolean = true,
    /** Position in Settings; lower = higher rank. */
    val order: Int = 0,
    val token: String? = null,
    val customHeaderName: String? = null,
    val customHeaderValue: String? = null,
    val allowTokenToMediaHosts: Boolean = false,
    /** User accepted sending the credential over plain http (§2.1 warning). */
    val allowTokenOverHttp: Boolean = false,
    /** Minutes; 0 = manual only (§15). */
    val refreshIntervalMin: Int = RefreshInterval.DEFAULT,
    /** Shipped test source (R12). Removable like any other source. */
    val isPreset: Boolean = false,
    val addedAt: Long = 0,
) {
    val auth: SourceAuth
        get() = SourceAuth(token, customHeaderName, customHeaderValue, allowTokenToMediaHosts, allowTokenOverHttp)

    /** Show the "not secure" mark (§2.1). */
    val isInsecure: Boolean get() = url.startsWith("http://", ignoreCase = true)

    val isAsset: Boolean get() = FeedUrls.isAsset(url)

    override fun toString(): String =
        "Source(id=$id, name=$name, url=<${if (isAsset) url else "redacted"}>, enabled=$enabled, order=$order, preset=$isPreset)"
}

object RefreshInterval {
    const val MANUAL = 0
    const val DEFAULT = 360
    /** The choices of §15, in minutes. */
    val CHOICES = listOf(15, 60, 360, 1440, MANUAL)
}

/** Preset test sources (R12). The files are generated by `scripts/feedgen/` into `app/src/main/assets/test-feeds/`. */
object PresetSources {
    data class Preset(val name: String, val url: String) {
        /** Stable id so backups and `src:` keys survive reinstalls. */
        val id: String get() = UUID.nameUUIDFromBytes(url.toByteArray()).toString()
    }

    val ALL = listOf(
        Preset("آزمایشی: فیلم‌های Blender", "asset:///test-feeds/blender.json"),
        Preset("آزمایشی: فیلم‌های آرشیو اینترنت", "asset:///test-feeds/archive-films.json"),
        Preset("آزمایشی: سریال‌های آرشیو اینترنت", "asset:///test-feeds/archive-series.json"),
        Preset("آزمایشی: پخش HLS چندکیفیتی", "asset:///test-feeds/hls-test.json"),
    )
}

/** On-disk form (Preferences DataStore, one JSON string). */
@Serializable
data class SourceRecord(
    val id: String,
    val name: String,
    val url: String,
    val enabled: Boolean = true,
    val order: Int = 0,
    val tokenEnc: String? = null,
    val headerName: String? = null,
    val headerValueEnc: String? = null,
    val allowTokenToMediaHosts: Boolean = false,
    val allowTokenOverHttp: Boolean = false,
    val refreshIntervalMin: Int = RefreshInterval.DEFAULT,
    val isPreset: Boolean = false,
    val addedAt: Long = 0,
)

@Serializable
data class SourcesFile(
    val version: Int = 1,
    val sources: List<SourceRecord> = emptyList(),
    /** Preset URLs that were seeded once; a preset the user deleted or disabled is never re-added/re-enabled. */
    val seededPresets: List<String> = emptyList(),
)
